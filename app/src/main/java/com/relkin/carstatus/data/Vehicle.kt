package com.relkin.carstatus.data

/** Чем «заправляется» транспорт: от этого зависят подписи, единицы и расчёт расхода. */
enum class Energy { FUEL, ELECTRIC, NONE }

/**
 * Вид транспорта: свой список расходников «из коробки», единицы заправки, наличие OBD2,
 * средний пробег в месяц, пока не накопится история.
 */
enum class VehicleKind(
    val label: String,
    val emoji: String,
    val energy: Energy,
    val hasObd: Boolean,
    val kmPerMonth: Int,
) {
    PETROL("Бензин", "🚗", Energy.FUEL, true, 1200),
    DIESEL("Дизель", "🚙", Energy.FUEL, true, 1500),
    ELECTRIC("Электромобиль", "🔋", Energy.ELECTRIC, true, 1200),
    MOTO("Мотоцикл", "🏍️", Energy.FUEL, true, 600),
    BICYCLE("Велосипед", "🚲", Energy.NONE, false, 200),
    EBIKE("Электровелосипед", "🚴", Energy.ELECTRIC, false, 300),
    ESCOOTER("Электросамокат", "🛴", Energy.ELECTRIC, false, 250);

    val isCar: Boolean get() = this == PETROL || this == DIESEL || this == ELECTRIC

    /** Единица заправки: литры или кВт·ч. */
    val unit: String get() = if (energy == Energy.ELECTRIC) "кВт·ч" else "л"
    /** «Заправка» / «Зарядка» — название записи. */
    val refuel: String get() = if (energy == Energy.ELECTRIC) "Зарядка" else "Заправка"
    /** «Топливо» / «Электричество» — категория расходов. */
    val energyLabel: String get() = if (energy == Energy.ELECTRIC) "Электричество" else "Топливо"
    /** «Здоровье авто» / «Здоровье мотоцикла»… */
    val healthOf: String get() = when (this) {
        PETROL, DIESEL, ELECTRIC -> "Здоровье авто"
        MOTO -> "Здоровье мотоцикла"
        BICYCLE, EBIKE -> "Здоровье велосипеда"
        ESCOOTER -> "Здоровье самоката"
    }
    val defaultTitle: String get() = when (this) {
        PETROL, DIESEL -> "Мой автомобиль"
        ELECTRIC -> "Мой электромобиль"
        MOTO -> "Мой мотоцикл"
        BICYCLE -> "Мой велосипед"
        EBIKE -> "Мой электровелосипед"
        ESCOOTER -> "Мой самокат"
    }

    val items: List<Item> get() = Consumables.of(this)

    companion object {
        fun of(name: String?): VehicleKind? = entries.firstOrNull { it.name == name }

        /** Для базы 0.1 (была только машина): угадываем по полю «Топливо». */
        fun guess(fuel: String): VehicleKind {
            val f = fuel.lowercase()
            return when {
                "диз" in f || "diesel" in f || "дт" == f.trim() -> DIESEL
                "электр" in f || "electr" in f || f.trim() == "ev" -> ELECTRIC
                else -> PETROL
            }
        }
    }
}

