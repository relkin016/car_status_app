/** Чем «заправляется» транспорт: от этого зависят подписи, единицы и расчёт расхода. */
enum class Energy { FUEL, ELECTRIC, NONE }

/**
 * Вид транспорта: свой список расходников «из коробки», единицы заправки, наличие OBD2,
 * средний пробег в месяц, пока не накопится история.
 */
enum class VehicleKind(
    private val ru: String,
    private val uk: String,
    val emoji: String,
    val energy: Energy,
    val hasObd: Boolean,
    val kmPerMonth: Int,
) {
    PETROL("Бензин", "Бензин", "🚗", Energy.FUEL, true, 1200),
    DIESEL("Дизель", "Дизель", "🚙", Energy.FUEL, true, 1500),
    ELECTRIC("Электромобиль", "Електромобіль", "🔋", Energy.ELECTRIC, true, 1200),
    MOTO("Мотоцикл", "Мотоцикл", "🏍️", Energy.FUEL, true, 600),
    BICYCLE("Велосипед", "Велосипед", "🚲", Energy.NONE, false, 200),
    EBIKE("Электровелосипед", "Електровелосипед", "🚴", Energy.ELECTRIC, false, 300),
    ESCOOTER("Электросамокат", "Електросамокат", "🛴", Energy.ELECTRIC, false, 250);

    val label: String get() = tr(ru, uk)

    val isCar: Boolean get() = this == PETROL || this == DIESEL || this == ELECTRIC

    /** Единица заправки: литры или кВт·ч. */
    val unit: String get() = if (energy == Energy.ELECTRIC) tr("кВт·ч", "кВт·год") else "л"
    /** «Заправка» / «Зарядка» — название записи. */
    val refuel: String get() = if (energy == Energy.ELECTRIC) tr("Зарядка", "Зарядка") else tr("Заправка", "Заправка")
    /** «Топливо» / «Электричество» — категория расходов. */
    val energyLabel: String get() = if (energy == Energy.ELECTRIC) tr("Электричество", "Електрика") else tr("Топливо", "Пальне")
    /** «Здоровье авто» / «Здоровье мотоцикла»… */
    val healthOf: String get() = when (this) {
        PETROL, DIESEL, ELECTRIC -> tr("Здоровье авто", "Здоров'я авто")
        MOTO -> tr("Здоровье мотоцикла", "Здоров'я мотоцикла")
        BICYCLE, EBIKE -> tr("Здоровье велосипеда", "Здоров'я велосипеда")
        ESCOOTER -> tr("Здоровье самоката", "Здоров'я самоката")
    }
    val defaultTitle: String get() = when (this) {
        PETROL, DIESEL -> tr("Мой автомобиль", "Мій автомобіль")
        ELECTRIC -> tr("Мой электромобиль", "Мій електромобіль")
        MOTO -> tr("Мой мотоцикл", "Мій мотоцикл")
        BICYCLE -> tr("Мой велосипед", "Мій велосипед")
        EBIKE -> tr("Мой электровелосипед", "Мій електровелосипед")
        ESCOOTER -> tr("Мой самокат", "Мій самокат")
    }

    val items: List<Item> get() = Consumables.of(this)

    companion object {
        fun of(name: String?): VehicleKind? = entries.firstOrNull { it.name == name }

        /** Для базы 0.1 (была только машина): угадываем по полю «Топливо». */
        fun guess(fuel: String): VehicleKind {
            val f = fuel.lowercase()
            return when {
                "диз" in f || "diesel" in f || "дт" == f.trim() -> DIESEL
                "электр" in f || "електр" in f || "electr" in f || f.trim() == "ev" -> ELECTRIC
                else -> PETROL
            }
        }
    }
}

