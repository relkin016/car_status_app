    /** Общие подсказки по диапазону, если конкретного кода нет в справочнике. */
    private fun byRange(code: String): Pair<String, String> {
        val sys = code[0]
        val generic = code[1] == '0' || code[1] == '2'
        val group = code.getOrNull(2)
        val p = when (sys) {
            'P' -> when (group) {
                '0', '1', '2' -> "Топливо и воздух (смесь, датчики впуска, форсунки)"
                '3' -> "Система зажигания или пропуски зажигания"
                '4' -> "Системы снижения токсичности (EGR, катализатор, EVAP)"
                '5' -> "Скорость, холостой ход, вспомогательные входы"
                '6' -> "Блок управления и его выходные цепи"
                '7', '8', '9' -> "Трансмиссия"
                'A', 'B', 'C' -> "Гибридная силовая установка"
                else -> "Силовой агрегат"
            }
            'C' -> "Шасси: ABS, ESP, подвеска, рулевое"
            'B' -> "Кузов: подушки безопасности, комфорт, климат"
            else -> "Сеть передачи данных между блоками"
        }
        return p to if (generic) "Общий (стандартный OBD2) код" else "Код производителя — расшифровку уточните по марке"
    }

    fun info(code: String): DtcInfo {
        known[code]?.let { (t, s, h) -> return DtcInfo(code, t, s, h) }
        val (group, kind) = byRange(code)
        return DtcInfo(code, group, 1, "$kind. Нет в справочнике приложения.")
    }

    fun severityLabel(s: Int) = when (s) {
        2 -> "Серьёзно — лучше не ехать / срочно в сервис"
        1 -> "Нужна диагностика в ближайшее время"
        else -> "Можно ездить, устранить при случае"
    }
